"""Explicit persistent workflow ports; return detached values, never ORM rows."""

from typing import Protocol, Self
from uuid import UUID

from scope_guard.domain.drafts.collection import DraftCollectionFilter


class WorkflowRepository(Protocol):
    async def draft_collection(
        self, owner: UUID, filters: DraftCollectionFilter, *, limit: int | None, offset: int = 0
    ) -> dict: ...
    async def draft_export_row(self, owner: UUID, identifier: UUID) -> dict: ...
    async def generation_event(self, owner, draft, operation, kind, phase, digest): ...
    async def legacy_revision(self, owner: UUID, identifier: UUID) -> dict: ...
    async def ready_exports_before(self, cutoff) -> list[dict]: ...
    async def expire_export(self, identifier: UUID, cutoff) -> bool: ...
    async def project(self, owner: UUID, identifier: UUID, *, lock: bool = False) -> dict: ...
    async def projects(self, owner: UUID, archived: bool = False) -> list[dict]: ...
    async def create_project(self, owner: UUID, values: dict, key: UUID, digest: str) -> dict: ...
    async def update_project(self, owner: UUID, identifier: UUID, values: dict) -> dict: ...
    async def draft(self, owner: UUID, identifier: UUID, *, lock: bool = False) -> dict: ...
    async def project_draft(self, owner: UUID, project: UUID) -> dict: ...
    async def save(
        self,
        owner: UUID,
        identifier: UUID,
        expected: int,
        operation: UUID,
        digest: str,
        changes: dict,
        reason: str,
        context: dict,
    ) -> dict: ...
    async def saved_operation(
        self, owner: UUID, draft: UUID, operation: UUID, digest: str
    ) -> dict | None: ...
    async def latest_materials(self, owner: UUID, draft: UUID, run: UUID) -> dict | None: ...
    async def revisions(self, owner: UUID, draft: UUID) -> list[dict]: ...
    async def revision(self, owner: UUID, draft: UUID, number: int) -> dict: ...
    async def create_run(
        self, owner: UUID, draft: dict, context: dict, parameters: dict, key: UUID, digest: str
    ) -> tuple[dict, bool]: ...
    async def run(self, owner: UUID, identifier: UUID) -> dict: ...
    async def finish_run(
        self,
        owner: UUID,
        identifier: UUID,
        status: str,
        result: dict | None,
        error: str | None = None,
    ) -> dict: ...
    async def histories(self, owner: UUID, project: UUID) -> list[dict]: ...
    async def history(self, owner: UUID, identifier: UUID) -> dict: ...
    async def complete(
        self, owner: UUID, draft: dict, context: dict, run: dict, key: UUID, digest: str
    ) -> dict: ...
    async def history_operation(
        self, owner: UUID, project: UUID, key: UUID, digest: str
    ) -> dict | None: ...
    async def agreement(self, owner: UUID, identifier: UUID) -> dict: ...
    async def agreements(self, owner: UUID, history: UUID) -> list[dict]: ...
    async def finalize(self, owner: UUID, history: dict, key: UUID, digest: str) -> dict: ...
    async def void(
        self, owner: UUID, identifier: UUID, expected: int, key: UUID, digest: str
    ) -> dict: ...
    async def export(self, owner: UUID, identifier: UUID) -> dict: ...
    async def exports(self, owner: UUID, agreement: UUID) -> list[dict]: ...
    async def create_export(self, owner: UUID, agreement: dict, key: UUID, digest: str) -> dict: ...
    async def retry_export(self, owner: UUID, identifier: UUID, key: UUID, digest: str) -> dict: ...
    async def evaluate(self, owner: UUID, run: dict, feedback: dict) -> dict: ...
    async def claim_export(self) -> dict | None: ...
    async def heartbeat(self, identifier: UUID, attempt: int) -> bool: ...
    async def export_outcome(
        self, claim: dict, metadata: dict | None, error: str | None
    ) -> bool: ...
    async def recover(self) -> None: ...
    async def referenced_objects(self) -> set[str]: ...


class WorkflowWork(Protocol):
    @property
    def workflow(self) -> WorkflowRepository: ...
    async def __aenter__(self) -> Self: ...
    async def __aexit__(self, exc_type, exc, traceback) -> None: ...
    async def commit(self) -> None: ...
