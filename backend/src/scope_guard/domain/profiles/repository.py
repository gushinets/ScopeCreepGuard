from typing import Protocol, Self
from uuid import UUID


class ProfileRepository(Protocol):
    async def onboarding(self, owner: UUID, event: str | None = None) -> dict: ...
    async def get(self, owner: UUID, *, lock: bool = False) -> dict: ...
    async def update(self, owner: UUID, expected: int, operation: UUID, changes: dict) -> dict: ...
    async def observe(self, owner: UUID): ...


class ProfilesWork(Protocol):
    profiles: ProfileRepository

    async def __aenter__(self) -> Self: ...
    async def __aexit__(self, exc_type, exc, traceback) -> None: ...
    async def commit(self) -> None: ...
